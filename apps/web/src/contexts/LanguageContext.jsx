const LanguageContext = createContext(null);

export const LanguageProvider = ({ children }) => {
  const [lang, setLangState] = useState(() => resolveInitialLanguage());
  // Custom label overrides loaded from platform_settings (nav_labels + button_labels).
  const [overrides, setOverrides] = useState({});

  const setLang = useCallback((next, opts = {}) => {
    const normalized = normalizeLangCode(next) || FALLBACK_LANG;
    setLangState(normalized);
    try {
      localStorage.setItem(STORAGE_LANG, normalized);
      if (opts.manual !== false) {
        // Default: any explicit setLang call is a user choice (picker, legacy toggle).
        // Pass { manual: false } only for silent system updates.
        if (opts.manual === true || opts.manual === undefined) {
          localStorage.setItem(STORAGE_LANG_MANUAL, '1');
        }
      }
      if (opts.manual === false) {
        localStorage.setItem(STORAGE_LANG_MANUAL, '0');
      }
    } catch {
      /* ignore */
    }
  }, []);

  const loadOverrides = useCallback((language) => {
    pb
      .collection('platform_settings')
      .getFullList({ sort: 'created' })
      .then((rows) => {
        if (!rows.length) return;
        const s = rows[0];
        const nav = (s.nav_labels && typeof s.nav_labels === 'object') ? s.nav_labels : {};
        const btn = (s.button_labels && typeof s.button_labels === 'object') ? s.button_labels : {};
        const merged = {};
        const base = String(language || '').split('-')[0];
        Object.entries(nav).forEach(([key, val]) => {
          if (val && typeof val === 'object') {
            if (val[language]) merged[key] = val[language];
            else if (val[base]) merged[key] = val[base];
          } else if (val) {
            merged[key] = val;
          }
        });
        Object.entries(btn).forEach(([key, val]) => {
          if (val && typeof val === 'object') {
            if (val[language]) merged[key] = val[language];
            else if (val[base]) merged[key] = val[base];
          } else if (val) {
            merged[key] = val;
          }
        });
        setOverrides(merged);
      })
      .catch(() => {});
  }, []);

  useEffect(() => {
    const rtl = isRtlLang(lang);
    const htmlLang = lang === 'zh-TW' ? 'zh-Hant' : lang === 'pt-BR' ? 'pt-BR' : lang;
    document.documentElement.lang = htmlLang;
    document.documentElement.dir = rtl ? 'rtl' : 'ltr';
    try {
      localStorage.setItem(STORAGE_LANG, lang);
    } catch {
      /* ignore */
    }
  }, [lang]);

  // Load Super Admin label overrides for the current language, and refresh
  // whenever the auth state changes (so labels apply right after login).
  useEffect(() => {
    loadOverrides(lang);
    return pb.authStore.onChange(() => loadOverrides(lang));
  }, [lang, loadOverrides]);

  // CMS slogan overrides (Control Center) — live without full page reload.
  const [cmsTick, setCmsTick] = useState(0);
  useEffect(() => {
    const onCms = () => setCmsTick((n) => n + 1);
    window.addEventListener('estatefollow-cms-updated', onCms);
    return () => window.removeEventListener('estatefollow-cms-updated', onCms);
  }, []);

  const isRtl = isRtlLang(lang);

  const t = useCallback(
    (key) => {
      if (overrides[key]) return overrides[key];
      try {
        const slogans = window.__EF_CMS__?.slogans;
        if (slogans) {
          const map = {
            brand_slogan: slogans.owner?.slogan_en,
            brand_slogan_ar_key: slogans.owner?.slogan_ar,
            brand_desc: slogans.owner?.desc_en,
            brand_subline: slogans.owner?.subline_en,
            brand_slogan_broker: slogans.broker?.slogan_en,
            brand_desc_broker: slogans.broker?.desc_en,
            brand_subline_broker: slogans.broker?.subline_en,
            brand_slogan_company: slogans.company?.slogan_en,
            brand_desc_company: slogans.company?.desc_en,
            brand_subline_company: slogans.company?.subline_en,
            login_title_owner: slogans.owner?.login_title_en,
            login_title_broker: slogans.broker?.login_title_en,
            login_title_company: slogans.company?.login_title_en,
            signup_owner: slogans.owner?.signup_title_en,
            signup_broker: slogans.broker?.signup_title_en,
            signup_company: slogans.company?.signup_title_en,
          };
          const arMap = {
            brand_slogan: slogans.owner?.slogan_ar,
            brand_desc: slogans.owner?.desc_ar,
            brand_subline: slogans.owner?.subline_ar,
            brand_slogan_broker: slogans.broker?.slogan_ar,
            brand_desc_broker: slogans.broker?.desc_ar,
            brand_subline_broker: slogans.broker?.subline_ar,
            brand_slogan_company: slogans.company?.slogan_ar,
            brand_desc_company: slogans.company?.desc_ar,
            brand_subline_company: slogans.company?.subline_ar,
            login_title_owner: slogans.owner?.login_title_ar,
            login_title_broker: slogans.broker?.login_title_ar,
            login_title_company: slogans.company?.login_title_ar,
            signup_owner: slogans.owner?.signup_title_ar,
            signup_broker: slogans.broker?.signup_title_ar,
            signup_company: slogans.company?.signup_title_ar,
          };
          const fromCms = lang === 'ar' ? arMap[key] : map[key];
          if (fromCms) return fromCms;
        }
      } catch {
        /* ignore */
      }
      const pack = translations[lang];
      const base = String(lang || '').split('-')[0];
      const basePack = base !== lang ? translations[base] : null;
      return (
        (pack && pack[key]) ||
        (basePack && basePack[key]) ||
        translations.en[key] ||
        key
      );
    },
    [lang, overrides, cmsTick],
  );

  const value = useMemo(
    () => ({ lang, setLang, t, isRtl }),
    [lang, setLang, t, isRtl],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};

export const useLanguage = () => useContext(LanguageContext);

export default LanguageContext;
